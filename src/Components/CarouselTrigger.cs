namespace ElementPlus
{
    /// <summary>
    /// 指示器触发方式，对齐 Element Plus <c>el-carousel</c> 的 <c>trigger</c> 属性。
    /// </summary>
    public enum CarouselTrigger
    {
        /// <summary>鼠标悬停指示器即切换（默认）。</summary>
        Hover = 0,

        /// <summary>点击指示器才切换。</summary>
        Click = 1
    }
}
